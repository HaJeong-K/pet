-- 실사업화를 위해 회원가입 화면에 약관 동의 체크박스를 추가하면서, "언제 동의했는지"
-- 증빙을 남기기 위한 컬럼입니다(개인정보보호법상 동의 증적 보관 목적). 이메일 회원가입/
-- 사장님 가입은 체크박스 동의 시각을 그대로 기록하고, 소셜 로그인(카카오/구글)은 최초
-- 로그인 시 자동 생성되는 users 행에도 동일하게 기록해 일관성을 맞춥니다.

alter table public.users add column if not exists agreed_terms_at timestamptz;

-- ⚠ 기존 회원(이미 가입된 행)은 실제 동의 시각을 알 수 없으니 NULL로 그대로 둡니다
-- (일괄로 지금 시각을 채워 넣지 않습니다 — 사실과 다른 증적이 되기 때문).
--
-- 새로 생성되는 행에는 기본값으로 now()가 채워지도록 해서, 카카오/구글 소셜 로그인처럼
-- 로그인 화면에 "계속 진행 시 약관에 동의로 간주" 안내만 두고 별도 체크박스가 없는
-- 경로에서도(KakaoMap.tsx, AuthGuard.tsx, place/[id]/page.tsx의 upsert들) 코드를
-- 따로 고치지 않고 자동으로 최초 생성 시각이 기록됩니다. upsert의 UPDATE 분기는 이
-- 컬럼을 건드리지 않으므로 이미 있는 값은 로그인할 때마다 바뀌지 않고 유지됩니다.
-- 이메일/사장님 가입은 체크박스 동의를 받은 시각을 명시적으로 넣으므로 이 기본값과
-- 무관하게 항상 정확합니다.
alter table public.users alter column agreed_terms_at set default now();
