/** 관광공사 "쇼핑" 장소의 이름 → 더 구체적인 분류(모르면 "쇼핑") */
export function tourShopCategory(name: string | null | undefined): string {
  const n = (name || "").trim();
  for (const [label, re] of RULES) if (re.test(n)) return label;
  return "쇼핑";
}

/** 쇼핑으로 묶어 다루는 분류인지 */
export const isTourShopCategory = (category: string | null | undefined): boolean =>
  !!category && (TOUR_SHOP_CATEGORIES as readonly string[]).includes(category);
