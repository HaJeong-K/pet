// 분류 이름이 바뀌어도 쇼핑으로 묶어 다루는 곳(말하듯이 검색 "쇼핑", 산책 코스 제외)은 TOUR_SHOP_CATEGORIES로 함께 봅니다.

export const TOUR_SHOP_CATEGORIES = ["쇼핑", "쇼핑몰 매장", "마트", "화장품", "안경원", "약국", "가전 매장", "의류·잡화", "서점·문구", "생활용품"] as const;

