import { describe, expect, it } from "vitest";
import { shortAddress } from "./shortAddress";

describe("목록 카드용 짧은 주소", () => {
  it.each([
    ["경기도 수원시 팔달구 행궁로 12", "팔달구 행궁로 12"],
    ["서울특별시 종로구 사직로 8", "종로구 사직로 8"],
    ["서울 종로구 사직로 8", "종로구 사직로 8"],
    ["부산광역시 해운대구 달맞이길 30", "해운대구 달맞이길 30"],
    ["경기도 가평군 가평읍 역전로 1", "가평군 가평읍 역전로 1"],
    ["경기도 파주시 문산읍 통일로 1", "문산읍 통일로 1"],
    ["제주특별자치도 제주시 한림읍 협재리 1", "한림읍 협재리 1"],
    ["강원특별자치도 강릉시 경강로 2100", "강릉시 경강로 2100"],
    ["세종특별자치시 한누리대로 2130", "한누리대로 2130"],
    ["서울특별시 중구 소공로 지하102 (남대문로2가)", "중구 소공로 지하102"],
  ])("%s → %s", (full, short) => {
    expect(shortAddress(full)).toBe(short);
  });
  it("빈 주소와 짧은 주소는 그대로 둔다", () => {
    expect(shortAddress(null)).toBe("");
    expect(shortAddress("서울")).toBe("서울");
  });
});
